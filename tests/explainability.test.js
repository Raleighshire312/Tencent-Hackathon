'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { explain, explainAudit, REASONS } = require('../src/explainability');

test('explain returns a friendly headline and detail for known codes', () => {
  const e = explain('USER_INJECTION_BLOCKED');
  assert.equal(e.tone, 'bad');
  assert.match(e.headline, /override/);
});

test('explain falls back gracefully for unknown codes', () => {
  const e = explain('NOT_A_REAL_CODE');
  assert.equal(e.code, 'NOT_A_REAL_CODE');
  assert.match(e.headline, /refused/);
});

test('explain accepts a { code, reasons } object and includes reasons', () => {
  const e = explain({ code: 'SEMANTIC_MISMATCH', reasons: ['amount differs', 'recipient differs'] });
  assert.equal(e.code, 'SEMANTIC_MISMATCH');
  assert.equal(e.matchedReasons.length, 2);
  assert.match(e.matchedReasons[0], /amount/);
});

test('every failure code generated by the codebase has an entry', () => {
  const codes = [
    'NO_TRANSFER_INTENTS','NO_INTENTS',
    'ADP_NOT_CONFIGURED','INVALID_MESSAGE','ADP_TIMEOUT','ADP_REQUEST_FAILED','ADP_RESPONSE_NOT_JSON',
    'ADP_RESPONSE_TOO_LARGE','ADP_TRANSCRIPT_HOSTILE','ADP_REFUSED',
    'STRUCTURE_NOT_OBJECT','STRUCTURE_REFUSAL_MISSING_REASON',
    'STRUCTURE_BAD_ACTION','STRUCTURE_BAD_RECIPIENT','STRUCTURE_BAD_SOURCE','STRUCTURE_BAD_CURRENCY',
    'STRUCTURE_BAD_AMOUNT','STRUCTURE_BAD_MINIMUM','STRUCTURE_BAD_VERIFICATION','STRUCTURE_BAD_RATIONALE',
    'USER_INJECTION_BLOCKED','USER_MESSAGE_TOO_LONG','USER_MESSAGE_OPAQUE','EMPTY_MESSAGE',
    'UNTRUSTED_INSTRUCTION_BLOCKED','SEMANTIC_MISMATCH','AMOUNT_RECIPIENT_MISMATCH',
    'RECIPIENT_NOT_IN_TEXT','SOURCE_ACCOUNT_MISMATCH','VERIFICATION_DOWNGRADE',
    'MINIMUM_BALANCE','INSUFFICIENT_FUNDS',
    'UNSUPPORTED_ACTION','INVALID_AMOUNT','UNSUPPORTED_CURRENCY','SOURCE_NOT_FOUND',
    'RECIPIENT_NOT_FOUND','RECIPIENT_AMBIGUOUS','RECIPIENT_UNVERIFIED','INVALID_CONSTRAINT',
    'VALIDATION_FAILED','INVALID_PROPOSAL','USER_REQUIRED','PROPOSAL_EXPIRED','PROPOSAL_TAMPERED',
    'INVALID_APPROVAL','APPROVAL_EXPIRED','APPROVAL_TAMPERED','ALREADY_EXECUTED',
    'RECIPIENT_VERIFICATION_LOST','AMBIGUOUS_REQUEST','SESSION_MISMATCH',
  ];
  for (const c of codes) assert.ok(REASONS[c], `missing REASONS[${c}] entry`);
});

test('explainAudit renders hash-chained entries as friendly rows', () => {
  const entries = [
    { at: 1, kind: 'interpret', payload: { code: 'EMPTY_MESSAGE' }, hash: 'h1' },
    { at: 2, kind: 'prepare',   payload: { code: 'PROPOSAL_TAMPERED' }, hash: 'h2' },
  ];
  const out = explainAudit(entries);
  assert.equal(out.length, 2);
  assert.match(out[0].summary.headline, /empty/i);
  assert.match(out[1].summary.headline, /tamper/i);
  assert.equal(out[0].fingerprint, null);
});
